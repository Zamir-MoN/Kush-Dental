import { describe, it, expect } from 'vitest';
import { formatMarkdownToHtml } from '../markdown';

describe('formatMarkdownToHtml XSS Sanitization', () => {
  it('allows safe markdown elements', () => {
    const raw = '# Title\n\n**Bold** and *Italic* and [Link](https://example.com)';
    const html = formatMarkdownToHtml(raw);
    expect(html).toContain('<h1>Title</h1>');
    expect(html).toContain('<strong>Bold</strong>');
    expect(html).toContain('<em>Italic</em>');
    expect(html).toContain('<a href="https://example.com"');
  });

  it('strips script tags', () => {
    const raw = 'Hello <script>alert(1)</script> World';
    const html = formatMarkdownToHtml(raw);
    expect(html).not.toContain('<script>');
    expect(html).not.toContain('alert(1)');
    expect(html).toContain('Hello  World');
  });

  it('strips javascript URLs in links', () => {
    const raw = '[Click Me](javascript:alert("xss"))';
    const html = formatMarkdownToHtml(raw);
    expect(html).not.toContain('javascript:');
  });

  it('strips on* event handlers', () => {
    const raw = '<img src="x" onerror="alert(1)" />';
    const html = formatMarkdownToHtml(raw);
    expect(html).not.toContain('onerror');
  });

  it('strips iframe and object tags', () => {
    const raw = 'Watch this: <iframe src="https://evil.com"></iframe>';
    const html = formatMarkdownToHtml(raw);
    expect(html).not.toContain('<iframe');
    expect(html).toContain('Watch this:');
  });

  it('preserves underline and strikethrough formatting exactly', () => {
    // 1. Testing native HTML generated by Tiptap
    const htmlRaw = '<p><u>Underline</u> and <s>Strike</s></p>';
    const htmlResult = formatMarkdownToHtml(htmlRaw);
    expect(htmlResult).toContain('<u>Underline</u>');
    expect(htmlResult).toContain('<s>Strike</s>');

    // 2. Testing strikethrough markdown
    const mdRaw = '~~Strikethrough~~ text';
    const mdResult = formatMarkdownToHtml(mdRaw);
    expect(mdResult).toContain('<s>Strikethrough</s>');
  });

  it('preserves html block tags without wrapping them in paragraphs', () => {
    // Testing that the markdown regex strip loop doesn't destroy existing HTML blocks
    const raw = '<h4>Heading 4</h4>\n<p>**Bold**</p>\n<blockquote>Quote</blockquote>';
    const html = formatMarkdownToHtml(raw);
    
    // It should NOT contain <p><h4>
    expect(html).not.toContain('<p><h');
    // It should correctly preserve the structural blocks
    expect(html).toContain('<h4>Heading 4</h4>');
    expect(html).toContain('<p><strong>Bold</strong></p>');
    expect(html).toContain('<blockquote>Quote</blockquote>');
  });
});
